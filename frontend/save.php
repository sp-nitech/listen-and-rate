// -- MUSHRA --------------------------------------------------------------

/**
 * Validate one MUSHRA rating's stimulus_id and value, mirroring
 * listen_and_rate/routers/api/mushra.py's _submit_mushra() per-item validation.
 *
 * @throws SaveRequestError (400) if the id is unknown, belongs to the
 *         reference system, or the rating is non-numeric or outside 0-100.
 * @return array the rated stimulus's metadata (system/item).
 */
function validate_mushra_rating(array $stimulusMap, array $r, ?string $referenceSystem): array
{
    $meta = $stimulusMap[$r['stimulus_id'] ?? ''] ?? null;
    if ($meta === null) {
        throw new SaveRequestError(400, 'Unknown stimulus ID in MUSHRA rating');
    }
    if ($referenceSystem !== null && $meta['system'] === $referenceSystem) {
        throw new SaveRequestError(400, "stimulus_id must not be the reference system's own stimulus");
    }
    // intval() would silently turn a non-numeric rating into 0 (a valid
    // score), so reject it explicitly - mirroring the FastAPI backend, where
    // Pydantic's int typing already refuses it.
    if (!is_numeric($r['rating'] ?? null)) {
        throw new SaveRequestError(400, 'MUSHRA rating must be a number');
    }
    $rating = intval($r['rating']);
    if ($rating < 0 || $rating > 100) {
        throw new SaveRequestError(400, "MUSHRA rating must be 0-100, got {$rating}");
    }
    return $meta;
}

/**
 * Validate that submitted MUSHRA ratings, grouped by item, cover every
 * rateable system, mirroring listen_and_rate/routers/api/mushra.py's
 * _submit_mushra() completeness check. Coverage only - a repeat collapses into
 * the same set, so "exactly once" is assert_answered_once()'s half of the job.
 *
 * @throws SaveRequestError (400) if any item is missing a system's rating or
 *         carries one for a system it should not.
 */
function validate_mushra_ratings_complete(array $stimulusMap, array $ratings, ?string $referenceSystem): void
{
    $rateableSystems = [];
    foreach ($stimulusMap as $meta) {
        $system = $meta['system'] ?? '';
        if ($system !== '' && $system !== $referenceSystem && !in_array($system, $rateableSystems, true)) {
            $rateableSystems[] = $system;
        }
    }
    sort($rateableSystems);

    $byItem = [];
    foreach ($ratings as $r) {
        $meta = $stimulusMap[$r['stimulus_id'] ?? ''] ?? null;
        if ($meta === null) {
            continue; // already rejected by validate_mushra_rating() above
        }
        $byItem[$meta['item']][$meta['system']] = true;
    }
    foreach ($byItem as $item => $systems) {
        $seen = array_keys($systems);
        sort($seen);
        if ($seen !== $rateableSystems) {
            throw new SaveRequestError(400, "Each item must rate every rateable system: {$item}");
        }
    }
}

// -- HTTP entry point ----------------------------------------------------

/** Handle the actual HTTP request: reads superglobals, writes headers/output. */
function handle_save_request(): void
{
    // Suppress PHP warnings/notices from corrupting JSON output.
    error_reporting(0);
    ini_set('display_errors', '0');

    // Use the server's actual timezone for the timestamp below, not whatever
    // (often UTC) PHP's own date.timezone ini setting happens to default to.
    date_default_timezone_set(detect_server_timezone());

    header('Content-Type: application/json; charset=utf-8');

    // Read output format/path, metadata field definitions, and the
    // AUTHORITATIVE test type from config_data.php - never trust the
    // client-submitted test_type for deciding how to validate/store.
    $config_data_path = __DIR__ . '/config_data.php';
    $config_data      = is_file($config_data_path) ? include $config_data_path : [];
    if (!is_array($config_data)) {
        $config_data = [];
    }

    $results_dir = resolve_results_dir(__DIR__, $config_data['output_path'] ?? null);

    // GET: pre-flight check - verify the results directory exists and is writable.
    if ($_SERVER['REQUEST_METHOD'] === 'GET') {
        if (!is_dir($results_dir) || !is_writable($results_dir)) {
            $reason = is_dir($results_dir) ? 'not writable' : 'missing or not accessible';
            http_response_code(503);
            echo json_encode(['error' =>
                "Results directory is {$reason}. "
                . "Run on the server: mkdir -p {$results_dir} && chmod 777 {$results_dir}"]);
            return;
        }
        echo json_encode(['status' => 'ok']);
        return;
    }

    if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
        http_response_code(405);
        echo json_encode(['error' => 'Method not allowed']);
        return;
    }

    $body = file_get_contents('php://input');
    $data = json_decode($body, true);

    $has_ratings = isset($data['ratings']) && is_array($data['ratings']);
    $has_choices = isset($data['choices']) && is_array($data['choices']);
    if (!is_array($data)
        || empty($data['session_id'])
        || empty($data['test_type'])
        || (!$has_ratings && !$has_choices)
    ) {
        http_response_code(422);
        echo json_encode(['error' => 'Invalid request body']);
        return;
    }

    try {
        $output_format = $config_data['output_format'] ?? 'csv';
        $test_type     = $config_data['test_type'] ?? 'mos';
        if (!in_array($test_type, ['mos', 'dmos', 'cmos', 'ab', 'abx', 'xab', 'mushra'], true)) {
            $test_type = 'mos';  // unrecognized config value: fall back to the default type
        }

        // Build stimulus lookup: id → {system, item} for enriching ratings.
        $stimulus_map_path = __DIR__ . '/stimulus_map.php';
        $stimulus_map = is_file($stimulus_map_path) ? include $stimulus_map_path : [];
        if (!is_array($stimulus_map)) {
            $stimulus_map = [];
        }

        $x_secret = hex2bin($config_data['x_secret'] ?? '');

        validate_submission_shape($test_type, $data);

        // CMOS, ABX, and XAB are absent here on purpose: their row builders
        // below (build_cmos_*/build_abx_*/build_xab_*) run the same per-choice
        // validation while building the rows, and every row is built before
        // anything is written - validating them here too would just do the
        // work twice.
        if ($test_type === 'mos') {
            validate_mos_ratings($stimulus_map, $data['ratings'] ?? []);
            validate_rating_range($data['ratings'] ?? []);
        } elseif ($test_type === 'dmos') {
            foreach ($data['ratings'] ?? [] as $r) {
                validate_dmos_rating($stimulus_map, $r, $config_data['reference_system'] ?? '');
            }
            validate_rating_range($data['ratings'] ?? []);
        } elseif ($test_type === 'ab') {
            validate_ab_choices($data['choices'] ?? [], $stimulus_map, $config_data['allow_tie'] ?? true);
        } elseif ($test_type === 'mushra') {
            foreach ($data['ratings'] ?? [] as $r) {
                validate_mushra_rating($stimulus_map, $r, $config_data['reference_system'] ?? null);
            }
            validate_mushra_ratings_complete(
                $stimulus_map,
                $data['ratings'] ?? [],
                $config_data['reference_system'] ?? null
            );
        }

        // Each form config is a {title, fields} block; only its fields drive
        // validation (the title is display-only, consumed by the frontend).
        $meta = validate_metadata(
            $config_data['metadata']['fields'],
            (is_array($data['metadata'] ?? null)) ? $data['metadata'] : []
        );
        // The post-test survey shares the metadata field schema and validator
        // (the two forms differ only in collection timing).
        $survey = validate_metadata(
            $config_data['survey']['fields'],
            (is_array($data['survey'] ?? null)) ? $data['survey'] : []
        );

        $experiment_dir  = resolve_experiment_dir($results_dir, experiment_id_for($config_data));
        assert_valid_id((string) $data['session_id'], 'session_id');
        $session_id_safe = $data['session_id'];
        // CSV columns are namespaced (metadata_*/survey_*, see prefix_keys);
        // the builders just lay out whatever keys they are handed, so the
        // merged prefixed map flows through them unchanged. JSON keeps the
        // raw keys inside its nested metadata/survey objects instead.
        $form      = array_merge(prefix_keys('metadata_', $meta), prefix_keys('survey_', $survey));
        $form_keys    = array_keys($form);
        $metrics_keys = enabled_metrics($config_data);
        // Baked in by `lar-export`. PHP cannot read the Python package's
        // version at request time, and the version that exported this bundle
        // is the one whose behaviour produced these results anyway.
        $tool_version = (string) ($config_data['tool_version'] ?? '');
        $ts        = date('c');

        if ($output_format === 'json') {
            $json_data = match ($test_type) {
                'mos', 'dmos' => build_json_result($data, $meta, $stimulus_map, $ts),
                'cmos' => build_cmos_json_result($data, $meta, $stimulus_map, $ts),
                'ab' => build_ab_json_result($data, $meta, $stimulus_map, $ts),
                'abx' => build_abx_json_result($data, $meta, $stimulus_map, $ts, $x_secret),
                'xab' => build_xab_json_result($data, $meta, $stimulus_map, $ts, $config_data['reference_system'] ?? ''),
                'mushra' => build_json_result($data, $meta, $stimulus_map, $ts),
            };
            // Survey answers and per-answer metrics are attached here, once,
            // rather than threaded through every per-test-type builder.
            $json_data['survey'] = $survey;
            // Every builder returns its rows under 'records', whatever key the
            // client sent them under - matching JSONResultSaver.
            $json_data['records'] = append_metrics_json(
                $json_data['records'],
                submitted_answers($test_type, $data),
                $metrics_keys
            );
            $json_data = order_result_keys($json_data, $tool_version);
            write_json_file($experiment_dir . '/' . $session_id_safe . '.json', $json_data);
        } else {
            [$fields, $rows] = match ($test_type) {
                'mos', 'dmos' => build_csv_rows($data, $form, $form_keys, $stimulus_map, $ts),
                'cmos' => build_cmos_csv_rows($data, $form, $form_keys, $stimulus_map, $ts),
                'ab' => build_ab_csv_rows($data, $form, $form_keys, $stimulus_map, $ts),
                'abx' => build_abx_csv_rows($data, $form, $form_keys, $stimulus_map, $ts, $x_secret),
                'xab' => build_xab_csv_rows($data, $form, $form_keys, $stimulus_map, $ts, $config_data['reference_system'] ?? ''),
                'mushra' => build_csv_rows($data, $form, $form_keys, $stimulus_map, $ts),
            };
            [$fields, $rows] = append_metrics_columns(
                $fields,
                $rows,
                submitted_answers($test_type, $data),
                $metrics_keys
            );
            [$fields, $rows] = prepend_tool_version_columns($fields, $rows, $tool_version);
            write_csv_file($experiment_dir . '/' . $session_id_safe . '.csv', $fields, $rows, $experiment_dir);
        }
    } catch (SaveRequestError $e) {
        http_response_code($e->status);
        echo json_encode(['error' => $e->getMessage()]);
        return;
    }

    echo json_encode(['status' => 'ok', 'session_id' => $data['session_id']]);
}

