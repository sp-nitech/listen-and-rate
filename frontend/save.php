/**
 * Validate one DMOS rating's stimulus_id/reference_id pair, mirroring
 * listen_and_rate/routers/api/dmos.py's _submit_dmos() validation.
 *
 * @throws SaveRequestError (400) if reference_id is missing, either id is
 *         unknown, they don't share an item, reference_id doesn't
 *         actually belong to the reference system, or stimulus_id does.
 * @return array the test stimulus's metadata (system/item) - the row
 *         to store is built from this, exactly like a MOS rating's.
 */
function validate_dmos_rating(array $stimulusMap, array $r, string $referenceSystem): array
{
    $referenceId = $r['reference_id'] ?? null;
    if ($referenceId === null) {
        throw new SaveRequestError(400, 'reference_id is required for DMOS ratings');
    }
    $testMeta = $stimulusMap[$r['stimulus_id'] ?? ''] ?? null;
    $refMeta  = $stimulusMap[$referenceId] ?? null;
    if ($testMeta === null || $refMeta === null) {
        throw new SaveRequestError(400, 'Unknown stimulus IDs in DMOS rating');
    }
    if ($testMeta['item'] !== $refMeta['item']) {
        throw new SaveRequestError(400, 'stimulus_id/reference_id do not share the same item');
    }
    if ($refMeta['system'] !== $referenceSystem) {
        throw new SaveRequestError(400, 'reference_id must belong to the reference system');
    }
    if ($testMeta['system'] === $referenceSystem) {
        throw new SaveRequestError(400, "stimulus_id must not be the reference system's own stimulus");
    }
    return $testMeta;
}

// -- CMOS ----------------------------------------------------------------

/**
 * Validate one CMOS choice's stimulus_ids pair and rating, mirroring
 * listen_and_rate/routers/api/cmos.py's _submit_cmos() validation. Reuses
 * validate_ab_choice_pair() for the pair itself, since CMOS pairs stimuli
 * the same way AB does (2 systems, same item).
 *
 * @throws SaveRequestError (400) if the pair is invalid/unknown, rating is
 *         missing, or rating is outside -3..3.
 * @return array{0: array, 1: array} [$meta1, $meta2] - metadata for
 *         stimulus_ids[0]/[1] respectively (order preserved, unlike AB,
 *         since CMOS's rating direction depends on it).
 */
function validate_cmos_choice(array $stimulusMap, array $c): array
{
    [$meta1, $meta2] = validate_ab_choice_pair($stimulusMap, $c['stimulus_ids'] ?? []);
    if (!array_key_exists('rating', $c) || $c['rating'] === null) {
        throw new SaveRequestError(400, 'rating is required for CMOS choices');
    }
    $rating = intval($c['rating']);
    if ($rating < -3 || $rating > 3) {
        throw new SaveRequestError(400, "CMOS rating must be -3 to 3, got {$rating}");
    }
    return [$meta1, $meta2];
}

/** Build the assoc array to json_encode for JSON-format CMOS output. */
function build_cmos_json_result(array $data, array $meta, array $stimulusMap, string $ts): array
{
    $enriched = [];
    foreach ($data['choices'] as $c) {
        [$meta1, $meta2] = validate_cmos_choice($stimulusMap, $c);
        $pair = [$meta1['system'], $meta2['system']];
        sort($pair, SORT_STRING);
        // $c['rating'] means "stimulus_ids[1] relative to stimulus_ids[0]";
        // flip its sign when stimulus_ids[0] isn't the canonical (system_a) side.
        $rating     = $meta1['system'] === $pair[0] ? intval($c['rating']) : -intval($c['rating']);
        $enriched[] = [
            'system_a'  => $pair[0],
            'system_b'  => $pair[1],
            'item' => $meta1['item'],
            'rating'    => $rating,
        ];
    }
    return [
        'session_id' => $data['session_id'],
        'timestamp'  => $ts,
        'test_type'  => $data['test_type'],
        'metadata'   => $meta,
        'records'    => $enriched,
    ];
}

/** Build [$fields, $rows] for CSV-format CMOS output. */
function build_cmos_csv_rows(array $data, array $meta, array $metaKeys, array $stimulusMap, string $ts): array
{
    $fields = array_merge(
        ['session_id', 'timestamp', 'test_type'],
        $metaKeys,
        ['system_a', 'system_b', 'item', 'rating']
    );
    $rows = [];
    foreach ($data['choices'] as $c) {
        [$meta1, $meta2] = validate_cmos_choice($stimulusMap, $c);
        $pair = [$meta1['system'], $meta2['system']];
        sort($pair, SORT_STRING);
        $rating = $meta1['system'] === $pair[0] ? intval($c['rating']) : -intval($c['rating']);
        $row    = [$data['session_id'], $ts, $data['test_type']];
        foreach ($metaKeys as $k) {
            $row[] = $meta[$k] ?? '';
        }
        $row[]  = $pair[0];
        $row[]  = $pair[1];
        $row[]  = $meta1['item'];
        $row[]  = $rating;
        $rows[] = $row;
    }
    return [$fields, $rows];
}

