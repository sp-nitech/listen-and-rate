// -- ABX -----------------------------------------------------------------

/**
 * Validate one ABX choice and resolve the ground truth via its x_token.
 *
 * @throws SaveRequestError (400) if the pair is invalid/unknown, the guess
 *         is missing or isn't one of the pair, or the x_token doesn't verify.
 * @return array{0: array, 1: array, 2: string} [$meta1, $meta2, $groundTruthId]
 */
function validate_abx_choice(array $stimulusMap, array $c, string $secret): array
{
    [$meta1, $meta2] = validate_ab_choice_pair($stimulusMap, $c['stimulus_ids'] ?? []);
    $selected = $c['selected_stimulus_id'] ?? null;
    if ($selected === null) {
        // ABX is forced-choice; unlike AB, null isn't a valid tie response.
        throw new SaveRequestError(400, 'selected_stimulus_id is required for ABX');
    }
    if (!in_array($selected, $c['stimulus_ids'], true)) {
        throw new SaveRequestError(400, 'selected_stimulus_id must be one of stimulus_ids');
    }
    [$id1, $id2] = $c['stimulus_ids'];
    $groundTruth = resolve_x($id1, $id2, $c['x_token'] ?? '', $secret);
    if ($groundTruth === null) {
        throw new SaveRequestError(400, 'Invalid or expired x_token');
    }
    return [$meta1, $meta2, $groundTruth];
}

/** Build the assoc array to json_encode for JSON-format ABX output. */
function build_abx_json_result(array $data, array $meta, array $stimulusMap, string $ts, string $secret): array
{
    $enriched = [];
    foreach ($data['choices'] as $c) {
        [$meta1, $meta2, $groundTruth] = validate_abx_choice($stimulusMap, $c, $secret);
        $pair = [$meta1['system'], $meta2['system']];
        sort($pair, SORT_STRING);
        $enriched[] = [
            'system_a'  => $pair[0],
            'system_b'  => $pair[1],
            'item' => $meta1['item'],
            'correct'   => $c['selected_stimulus_id'] === $groundTruth,
        ];
    }
    return [
        'session_id' => $data['session_id'],
        'timestamp'  => $ts,
        'test_type'  => $data['test_type'],
        'metadata'   => $meta,
        'records'    => $enriched,
    ];
}

/** Build [$fields, $rows] for CSV-format ABX output. */
function build_abx_csv_rows(array $data, array $meta, array $metaKeys, array $stimulusMap, string $ts, string $secret): array
{
    $fields = array_merge(
        ['session_id', 'timestamp', 'test_type'],
        $metaKeys,
        ['system_a', 'system_b', 'item', 'correct']
    );
    $rows = [];
    foreach ($data['choices'] as $c) {
        [$meta1, $meta2, $groundTruth] = validate_abx_choice($stimulusMap, $c, $secret);
        $pair = [$meta1['system'], $meta2['system']];
        sort($pair, SORT_STRING);
        $row = [$data['session_id'], $ts, $data['test_type']];
        foreach ($metaKeys as $k) {
            $row[] = $meta[$k] ?? '';
        }
        $row[]  = $pair[0];
        $row[]  = $pair[1];
        $row[]  = $meta1['item'];
        // Matches Python's str(True)/str(False), since storage.py's CSV
        // writer does the same for the equivalent MOS/AB row shape's values.
        // JSON-style lowercase tokens, matching the JSON output's native
        // boolean and Python's CSVResultSaver (see storage._csv_cell).
        $row[]  = ($c['selected_stimulus_id'] === $groundTruth) ? 'true' : 'false';
        $rows[] = $row;
    }
    return [$fields, $rows];
}

