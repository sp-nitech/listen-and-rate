/**
 * Validate one XAB choice's stimulus_ids pair and selection, mirroring
 * listen_and_rate/routers/api/xab.py's _submit_xab() validation. Reuses
 * validate_ab_choice_pair() for the pair itself; additionally rejects a
 * pair containing the reference system's stimulus (the rated pair must be
 * the two test systems) and a missing selection (forced choice - no tie).
 *
 * @throws SaveRequestError (400) if the pair is invalid/unknown, includes
 *         the reference stimulus, or the selection is missing/outside it.
 * @return array{0: array, 1: array} [$meta1, $meta2]
 */
function validate_xab_choice(array $stimulusMap, array $c, string $referenceSystem): array
{
    [$meta1, $meta2] = validate_ab_choice_pair($stimulusMap, $c['stimulus_ids'] ?? []);
    if ($meta1['system'] === $referenceSystem || $meta2['system'] === $referenceSystem) {
        throw new SaveRequestError(400, "stimulus_ids must not include the reference system's stimulus");
