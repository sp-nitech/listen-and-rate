    $selected = $c['selected_stimulus_id'] ?? null;
    if ($selected === null) {
        throw new SaveRequestError(400, 'selected_stimulus_id is required for XAB');
    }
    if (!in_array($selected, $c['stimulus_ids'], true)) {
        throw new SaveRequestError(400, 'selected_stimulus_id must be one of stimulus_ids');
    }
    return [$meta1, $meta2];
}

