/**
 * Validate all submitted AB choices, mirroring
 * listen_and_rate/routers/api/ab.py's _submit_ab() validation.
 *
 * @throws SaveRequestError (400) on an invalid pair, a selected_stimulus_id
 *         outside the pair, or a disallowed tie.
 */
function validate_ab_choices(array $choices, array $stimulusMap, bool $allowTie): void
{
    foreach ($choices as $c) {
        validate_ab_choice_pair($stimulusMap, $c['stimulus_ids'] ?? []);
        $selected = $c['selected_stimulus_id'] ?? null;
        if ($selected !== null && !in_array($selected, $c['stimulus_ids'], true)) {
            throw new SaveRequestError(400, 'selected_stimulus_id must be one of stimulus_ids');
        }
        if ($selected === null && !$allowTie) {
            throw new SaveRequestError(400, 'Ties are not allowed for this test');
        }
    }
}

/**
 * Positional outcome token for an AB choice: OUTCOME_TIE when nothing was
 * selected, else OUTCOME_A/OUTCOME_B for the chosen side of the sorted pair.
 * Mirrors listen_and_rate/routers/api/ab.py so any system name is safe.
 */
function ab_winner_token(?string $selected, array $stimulusMap, array $pair): string
{
    if ($selected === null) {
        return OUTCOME_TIE;
    }
    return $stimulusMap[$selected]['system'] === $pair[0] ? OUTCOME_A : OUTCOME_B;
}

