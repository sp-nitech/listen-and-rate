        $enriched[] = [
            'system_a'  => $pair[0],
            'system_b'  => $pair[1],
            'item' => $meta1['item'],
            'winner'    => ab_winner_token($selected, $stimulusMap, $pair),
        ];
    }
    return [
        'session_id' => $data['session_id'],
        'timestamp'  => $ts,
        'test_type'  => $data['test_type'],
        'metadata'   => $meta,
        'records'    => $enriched,
    ];
}

